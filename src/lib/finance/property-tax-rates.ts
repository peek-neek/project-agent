/** The rate for a city name from the report (case and "City of" tolerant). */
export function propertyTaxRateFor(city: string | null | undefined) {
  if (!city) return null;
  const clean = city
    .replace(/^(city|town|township|municipality) of /i, "")
    .trim()
    .toLowerCase();
  const hit = Object.keys(PROPERTY_TAX_RATES).find(
    (k) => k.toLowerCase() === clean,
  );
  return hit ? { name: hit, rate: PROPERTY_TAX_RATES[hit] } : null;
}
